package ai.singlr.sail.engine;

import ai.singlr.sail.common.Remedy;
import java.io.IOException;
import java.util.Objects;
import java.util.concurrent.TimeoutException;

/**
 * Installs {@code ~/.sail/bin/skill}, the per-container helper that lists and reads a project's
 * skills where the work happens. It calls the host's API over the same socket and credential as
 * {@code spec} ({@link SocketPreamble}). Sharing and removing one are a person's, from outside the
 * container, since whatever runs in it can read its credential: the host refuses both to every
 * credential in a container and names the host command that takes them, which reads the folder from
 * the container itself.
 */
public final class SkillCliHelper {

  /** Container-side path of the helper script, beside {@code spec} on the PATH. */
  public static final String SCRIPT_PATH = SpecCliHelper.SCRIPT_DIR + "/skill";

  private static final String SCRIPT =
      """
      #!/usr/bin/env bash
      # Generated by sail. Read this project's skills, which every agent and every box sees,
      # over the bind-mounted API socket. Dependency-free: bash + curl, no jq.
      set -euo pipefail

      __PREAMBLE__
      BASE="http://sail/v1/projects/$PROJECT/skills"

      usage() {
        cat >&2 <<'USAGE'
      skill — read this project's skills (Agent Skills folders), which every agent and every box sees

        skill ls                        every skill an agent here can see, and where each comes from (JSON)
        skill show <name>               a skill's SKILL.md (JSON: skill_md)

      Sharing a skill is a person's, from outside the container: on the host,
        __SHARE__
        __UNSHARE__
      or in Mast.
      USAGE
        exit "${1:-0}"
      }

      require_name() {
        case "$1" in
          ""|*[!a-z0-9-]*) die "'$1' is not a skill name: lowercase letters, digits and hyphens";;
        esac
      }

      cmd="${1:-}"; [ $# -gt 0 ] && shift || true
      case "$cmd" in
        ls)
          api "$BASE";;
        show)
          [ $# -ge 1 ] || die "show needs a skill name"
          require_name "$1"
          api "$BASE/$1";;
        add)
          [ $# -ge 1 ] || die "add needs a folder"
          folder="$(CDPATH= cd -P -- "$1" 2>/dev/null && pwd -P)" || die "Not a folder: $1"
          shift
          FIELDS=(--data-urlencode "folder=$folder")
          while [ $# -gt 0 ]; do
            case "$1" in
              --name) [ $# -ge 2 ] || die "--name needs a skill name"; require_name "$2"; FIELDS+=(--data-urlencode "name=$2"); shift 2;;
              *) die "add accepts only --name <name>";;
            esac
          done
          api -X POST "${FIELDS[@]}" "$BASE";;
        rm)
          [ $# -ge 1 ] || die "rm needs a skill name"
          require_name "$1"
          api -X DELETE "$BASE/$1";;
        ""|-h|--help) usage 0;;
        *) die "unknown command: $cmd (try 'skill --help')";;
      esac
      """;

  private final ShellExec shell;

  public SkillCliHelper(ShellExec shell) {
    this.shell = Objects.requireNonNull(shell, "shell");
  }

  /** The script {@link #install(String)} writes. Pure function. */
  public static String scriptContent() {
    return SCRIPT
        .replace("__PREAMBLE__\n", SocketPreamble.of("skill"))
        .replace(
            "__SHARE__", Remedy.of(StageSkill.shareFromContainer("<folder>", "<project>")).plain())
        .replace("__UNSHARE__", Remedy.of(StageSkill.unshare("<skill>", "<project>")).plain());
  }

  /** Installs the helper at {@link #SCRIPT_PATH} in {@code container}, idempotently. */
  public void install(String container) throws IOException, InterruptedException, TimeoutException {
    SpecCliHelper.installOnPath(shell, container, SCRIPT_PATH, scriptContent());
  }
}
