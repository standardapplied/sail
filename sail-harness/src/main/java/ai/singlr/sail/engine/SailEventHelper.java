package ai.singlr.sail.engine;

import ai.singlr.sail.harness.Harnesses;
import java.io.IOException;
import java.util.List;
import java.util.Objects;
import java.util.concurrent.TimeoutException;

/**
 * Installs and locates {@code ~/.sail/bin/sail-event.sh}, the per-container shell helper that agent
 * hooks invoke to publish events to the host {@code sail-api} over the bind-mounted Unix socket at
 * {@link SailPaths#apiSocketContainerPath()}.
 *
 * <p>The script is intentionally tiny: bash and curl, and python3 for the one hook whose payload it
 * must read. It builds a minimal {@link ai.singlr.sail.api.Event}-shaped JSON body and POSTs it
 * best-effort — failures (socket missing, sail-api restarting) are swallowed so a transient host
 * hiccup never blocks an agent.
 *
 * <p>Its first argument is an event type, with one exception: {@link #BATCH_RESOLVED}, for the hook
 * a CLI fires when an agent's batch of tool calls has resolved. That is posted as {@code
 * agent_tool_finished} carrying {@code batch: true}, so every reader of tool events takes it for
 * the progress it is and only the watcher, which counts calls in flight, reads it as "none are". A
 * subagent's batches say nothing of the calls its parent still waits on, so the script posts
 * nothing for a hook payload that names an {@code agent_id} — and nothing where it cannot tell,
 * python3 missing or the payload unreadable.
 */
public final class SailEventHelper {

  /** Container-side path of the helper script. */
  public static final String SCRIPT_PATH = "/home/dev/.sail/bin/sail-event.sh";

  /**
   * The script argument, in place of an event type, for the end of an agent's batch of tool calls.
   */
  public static final String BATCH_RESOLVED = "batch-resolved";

  /** Container-side parent directory of {@link #SCRIPT_PATH}. */
  public static final String SCRIPT_DIR = "/home/dev/.sail/bin";

  private static final String SCRIPT =
      """
      #!/usr/bin/env bash
      # Generated by sail. Posts one lifecycle event to the sail-api Unix socket.
      #   Args: <event-type> [reason]
      # __BATCH_RESOLVED__ in place of an event type is posted as agent_tool_finished with
      # data.batch=true, and only for the main agent: a hook payload naming an agent_id is a
      # subagent's.
      # The optional reason lands in data.reason, sanitized to keep the
      # hand-built JSON valid (quotes, backslashes, control chars dropped).
      # The run credential (SAIL_RUN_CREDENTIAL, injected at launch) both authenticates the
      # request and scopes it: the server stamps project/spec/run/author from the authenticated
      # run and ignores the fields below. No credential means an untracked engineer session with
      # no run to speak for — skip silently so ad-hoc 'claude' invocations never pollute the spec
      # event bus. Every sail-launched run carries one, whichever lane launched it, so a
      # reviewer's and a fix agent's tool calls reach the bus as a build's do. SAIL_SPEC_ID
      # rides along only as an advisory hint.
      set -eu

      EVENT_TYPE="${1:?event type required}"
      REASON="$(printf '%s' "${2:-}" | tr -d '\\\\"\\000-\\037')"
      CREDENTIAL="${SAIL_RUN_CREDENTIAL:-}"
      if [ -z "$CREDENTIAL" ]; then
        exit 0
      fi
      BATCH=""
      if [ "$EVENT_TYPE" = "__BATCH_RESOLVED__" ]; then
        command -v python3 >/dev/null 2>&1 || exit 0
        python3 -c 'import json, sys; sys.exit(1 if json.load(sys.stdin).get("agent_id") else 0)' \\
          2>/dev/null || exit 0
        EVENT_TYPE="agent_tool_finished"
        BATCH="yes"
      fi
      SPEC_ID="${SAIL_SPEC_ID:-}"
      AGENT="${SAIL_AGENT:-__DEFAULT_AGENT__}"
      RUN_ID="${SAIL_RUN_ID:-}"
      RUN_ROLE="${SAIL_RUN_ROLE:-}"
      PROJECT="$(hostname)"
      HOST="$(hostname)"
      TS="$(date -u +%Y-%m-%dT%H:%M:%SZ)"
      SOCKET="__SAIL_API_SOCKET__"

      if [ ! -S "$SOCKET" ]; then
        exit 0
      fi

      FIELDS=""
      if [ -n "$RUN_ID" ]; then
        FIELDS="\\"run_id\\":\\"$RUN_ID\\""
      fi
      if [ -n "$RUN_ROLE" ]; then
        FIELDS="$FIELDS${FIELDS:+,}\\"run_role\\":\\"$RUN_ROLE\\""
      fi
      if [ -n "$REASON" ]; then
        FIELDS="$FIELDS${FIELDS:+,}\\"reason\\":\\"$REASON\\""
      fi
      if [ -n "$BATCH" ]; then
        FIELDS="$FIELDS${FIELDS:+,}\\"batch\\":true"
      fi
      DATA="{$FIELDS}"
      BODY="{\\"v\\":1,\\"ts\\":\\"$TS\\",\\"project\\":\\"$PROJECT\\",\\"spec\\":\\"$SPEC_ID\\",\\"type\\":\\"$EVENT_TYPE\\",\\"agent\\":\\"$AGENT\\",\\"host\\":\\"$HOST\\",\\"data\\":$DATA}"

      curl --silent --max-time 5 \\
        --unix-socket "$SOCKET" \\
        -H 'Content-Type: application/json' \\
        -H "Authorization: Bearer $CREDENTIAL" \\
        -X POST -d "$BODY" \\
        http://sail/v1/events >/dev/null 2>&1 || true
      """;

  private final ShellExec shell;

  public SailEventHelper(ShellExec shell) {
    this.shell = Objects.requireNonNull(shell, "shell");
  }

  /** Returns the script content that {@link #install(String)} writes. Pure function. */
  public static String scriptContent() {
    return SCRIPT
        .replace("__SAIL_API_SOCKET__", SailPaths.apiSocketContainerPath().toString())
        .replace("__BATCH_RESOLVED__", BATCH_RESOLVED)
        .replace("__DEFAULT_AGENT__", Harnesses.DEFAULT.yamlName());
  }

  /**
   * Idempotently installs the helper script at {@link #SCRIPT_PATH} inside the given container,
   * chmod 0755, owned by the dev user.
   */
  public void install(String container) throws IOException, InterruptedException, TimeoutException {
    NameValidator.requireValidProjectName(container);

    var mkdir = shell.exec(ContainerExec.asDevUser(container, List.of("mkdir", "-p", SCRIPT_DIR)));
    if (!mkdir.ok()) {
      throw new IOException(
          "Failed to create " + SCRIPT_DIR + " in " + container + ": " + mkdir.stderr());
    }

    var write =
        shell.exec(
            ContainerExec.asDevUser(
                container,
                List.of(
                    "bash",
                    "-c",
                    "printf '%s' \"$1\" > \"$2\" && chmod 0755 \"$2\"",
                    "bash",
                    scriptContent(),
                    SCRIPT_PATH)));
    if (!write.ok()) {
      throw new IOException(
          "Failed to install " + SCRIPT_PATH + " in " + container + ": " + write.stderr());
    }
  }
}
