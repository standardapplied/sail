package ai.singlr.sail.engine;

import ai.singlr.sail.store.BlobStore;
import java.io.ByteArrayInputStream;
import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.util.LinkedHashMap;
import java.util.Map;

/**
 * Sail's {@code sail-portal} skill: how any agent brings its project's app up, sees whether each
 * declared port listens, reads why a process failed, and stops it, through {@code scripts/portal},
 * which calls the host's stack routes over the container's socket as {@code spec} does. It is
 * installed whole beside {@code spec-board} into every harness's skills folder, so an agent asked
 * to "start the app" does what Mast's Portal button does, in Claude Code, Codex or any harness
 * added later.
 */
public final class PortalSkill {

  /** The skill's name, which is its folder's. */
  public static final String NAME = "sail-portal";

  /** The script's path in the skill's folder. */
  public static final String SCRIPT = "scripts/portal";

  private static final String SKILL_MD =
      """
      ---
      name: sail-portal
      description: >
        Bring this project's app up, see whether each of its ports listens, read why a process
        failed, and stop it. Use when someone asks to run, start, open, preview or check the app or
        its API, after changing code the running app serves, or when the person mentions the portal.
      ---

      The project declares how it comes up: its services and its processes, each process with the
      command that starts it and the port it listens on. Sail runs each process as a unit of its
      own, and Mast's Portal forwards the ports to the person's machine and opens the browser.
      This skill does the same from here, with `scripts/portal` beside this file.

      ## Commands

      - `scripts/portal up [seconds]` brings the services and processes up and waits, 60 seconds by
        default, until every declared port listens or its process exits. It prints each port as
        JSON: `name`, `port`, `kind` (service or process), `state` (listening, starting, exited,
        stopped or timeout), `exit_code` and `detail` (the last line an exited process wrote).
      - `scripts/portal ports` prints the same without starting anything.
      - `scripts/portal log <process> [lines]` prints the end of a process's log, 50 lines by
        default.
      - `scripts/portal stop` stops the processes; the services keep running.

      ## How to use it

      1. When the person asks to run, see or open the app, run `scripts/portal up`. When every port
         listens, tell them, and that Mast's Portal opens it in their browser.
      2. When a port's state is `exited`, run `scripts/portal log <process>`, find the cause, fix it
         (a missing dependency, a wrong command, a port already taken), and run `scripts/portal up`
         again. Say what you fixed.
      3. After you change code the running app serves, run `scripts/portal up` again: a process
         whose command changed restarts, and an unchanged one keeps running.
      4. Never start a declared process yourself (`npm run dev &` and the like): its unit owns the
         port, and a second copy fights it for it.
      5. When `up` lists no process with a port, the project does not declare how its app comes up.
         Find the command that starts the app and the port it listens on in the repo (its
         `package.json` scripts, its build file, its README), and give the person the exact entry to
         add to the project's definition, for example:

         ```yaml
         processes:
           web:
             command: npm run dev
             workdir: web
             port: 3000
         ```

         You cannot change the definition yourself: the person adds it, and `up` then brings it
         up.
      6. A refusal names why: a read-only session cannot bring the app up or stop it, and a stopped
         container says how to start it. Tell the person what it said.
      """;

  private static final String SCRIPT_TEXT =
      """
      #!/usr/bin/env bash
      # Generated by sail. Bring this project's app up and read its ports over the bind-mounted API
      # socket. Dependency-free: bash + curl, no jq.
      set -euo pipefail

      __PREAMBLE__
      BASE="http://sail/v1/projects/$PROJECT"
      LOGS="$HOME/.sail/processes"

      usage() {
        cat >&2 <<'USAGE'
      portal — bring this project's app up and see what listens where (JSON)

        portal up [seconds]          start the services and processes, wait for every port (default 60)
        portal ports                 where each declared port stands, starting nothing
        portal log <process> [lines] the end of a process's log (default 50 lines)
        portal stop                  stop the processes; the services keep running
      USAGE
        exit "${1:-0}"
      }

      require_number() {
        case "$1" in
          ""|*[!0-9]*) die "'$1' is not a number";;
        esac
      }

      cmd="${1:-}"; [ $# -gt 0 ] && shift || true
      case "$cmd" in
        up)
          seconds="${1:-60}"
          require_number "$seconds"
          api --max-time "$((seconds + 30))" -X POST --data-urlencode "timeout=$seconds" "$BASE/serve";;
        ports)
          api "$BASE/ports";;
        stop)
          api -X DELETE "$BASE/serve";;
        log)
          [ $# -ge 1 ] || die "log needs a process name"
          case "$1" in
            ""|[!a-zA-Z0-9]*|*[!a-zA-Z0-9._-]*) die "'$1' is not a process name";;
          esac
          lines="${2:-50}"
          require_number "$lines"
          [ -f "$LOGS/$1.log" ] || die "process '$1' has no log yet: it has not run. Run: portal up"
          tail -n "$lines" -- "$LOGS/$1.log";;
        ""|-h|--help) usage 0;;
        *) die "unknown command: $cmd (try 'portal --help')";;
      esac
      """;

  private static final Map<String, Integer> MODES = Map.of(StageSkill.MANIFEST, 0644, SCRIPT, 0755);

  private PortalSkill() {}

  /** The skill: its {@code SKILL.md} and its script. */
  public static StageSkill skill() {
    return StageSkill.of(
        NAME,
        SKILL_MD,
        files().entrySet().stream()
            .map(
                entry -> {
                  var bytes = entry.getValue().getBytes(StandardCharsets.UTF_8);
                  return new StageSkill.File(
                      entry.getKey(),
                      BlobStore.hash(bytes),
                      bytes.length,
                      MODES.get(entry.getKey()));
                })
            .toList());
  }

  /** The bytes of {@code file} of the skill. */
  public static InputStream content(StageSkill.File file) {
    var text = files().get(file.path());
    if (text == null) {
      throw new IllegalArgumentException(NAME + " has no file " + file.path() + ".");
    }
    return new ByteArrayInputStream(text.getBytes(StandardCharsets.UTF_8));
  }

  /** The text of the skill's {@code SKILL.md}. */
  public static String skillMd() {
    return SKILL_MD;
  }

  /** The text of {@code scripts/portal}. */
  public static String script() {
    return SCRIPT_TEXT.replace("__PREAMBLE__\n", SocketPreamble.of("portal"));
  }

  private static Map<String, String> files() {
    var files = new LinkedHashMap<String, String>();
    files.put(StageSkill.MANIFEST, SKILL_MD);
    files.put(SCRIPT, script());
    return files;
  }
}
