package ai.singlr.sail.engine;

import ai.singlr.sail.store.FdeSshKeyStore;
import java.util.List;
import java.util.regex.Pattern;

/**
 * Renders the {@code sail} user's {@code authorized_keys} from the registry. Each registered key
 * becomes a forced-command line that pins it to the gateway for exactly one person, by this box's
 * id for them, never by handle: a handle can be moved aside or given to someone new, and the line
 * must then fail, not open the door for whoever holds the name.
 *
 * <pre>{@code
 * command="/usr/local/bin/sail _gateway --fde-id fde_01J...",restrict ssh-ed25519 AAAA... uday@laptop
 * }</pre>
 *
 * <p>The id is interpolated inside the {@code command="..."} quotes, so one containing a quote or
 * whitespace could break out and inject options. The renderer is therefore fail-closed: it rejects
 * any id that is not a conservative {@code [A-Za-z0-9._-]+}, refusing to emit the whole file rather
 * than write a line that could widen what a key may run.
 */
public final class AuthorizedKeysRenderer {

  private static final Pattern SAFE_ID = Pattern.compile("[A-Za-z0-9._-]+");
  private static final String HEADER =
      "# Managed by sail — regenerated by '"
          + OperatorCommand.SUDO.sail("host keys sync")
          + "'. Do not edit by hand.";

  private AuthorizedKeysRenderer() {}

  public static String render(List<FdeSshKeyStore.SshKeyInfo> keys, String sailBinary) {
    var out = new StringBuilder(HEADER).append('\n');
    for (var key : keys) {
      if (!SAFE_ID.matcher(key.fdeId()).matches()) {
        throw new IllegalArgumentException(
            "Refusing to render authorized_keys: unsafe FDE id '" + key.fdeId() + "'.");
      }
      out.append("command=\"")
          .append(sailBinary)
          .append(" _gateway --fde-id ")
          .append(key.fdeId())
          .append("\",restrict ")
          .append(key.publicKey())
          .append('\n');
    }
    return out.toString();
  }
}
